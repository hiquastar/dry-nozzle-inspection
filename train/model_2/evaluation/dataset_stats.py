"""
dataset_stats.py - every number in thesis Section 4.1 (Data and Annotation)
comes from here. Reads the three split files and writes

  results/dataset_stats.json                       all numbers
  papers/thesis/Chapters/table-and-figure/tab-ch4-class-dist.tex   class table  (\input in Chapter04)
  papers/thesis/Chapters/table-and-figure/tab-ch4-sources.tex      per-source table

Run from train/model_2:   python evaluation/dataset_stats.py
Static-scene analysis (near-duplicate runs) uses the 640x480 image cache.
"""

import collections
import hashlib
import json
import statistics as st
import sys
from pathlib import Path

import cv2
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "structure"))
from config import EXCLUDED_CATS, REPO_ROOT, TEST_JSON, TRAIN_JSON, VAL_JSON  # noqa: E402
from dataset import cache_path_for, resolve_image_path  # noqa: E402

OUT_JSON = HERE.parent / "results" / "dataset_stats.json"
GEN_DIR = REPO_ROOT / "papers" / "thesis" / "Chapters" / "table-and-figure"
GEN_DIR.mkdir(parents=True, exist_ok=True)

# Class names are taken from ann["_meta"]["original_class"], exactly as
# structure/dataset.py does. The category_id column of the merged split files
# is NOT reliable: the per-source Roboflow exports number their classes
# differently (CAM1-V3 / CAM2-V3 have no buildup slot, so their ids 2/3 mean
# facing/no_spray) and create_splits_reverse.py copies ids unchanged. Counting
# by id would invent a 'buildup' class of 3,473 boxes that does not exist.
CLASS_ORDER = ["nozzle_spray", "nozzle_facing", "nozzle_no_spray", "big_nozzle"]
THESIS_NAME = {"nozzle_spray": "spray", "nozzle_facing": "facing", "nozzle_no_spray": "no\\_spray",
               "big_nozzle": "big", "nozzle_buildup": "buildup"}
# thesis naming of the dated sessions (Chapter 5 calls them CAM3)
SOURCE_LABEL = {"20250508": "CAM3 - V1", "20250509": "CAM3 - V2", "20250510": "CAM3 - V3"}
STATIC_THRESH = 1.0  # mean |diff| on a 64x48 thumbnail below this = same scene


def fmt(n):
    return f"{n:,}".replace(",", "{,}")


def latex_table(title, caption, label, colspec, header, body, footer, stretch=1.2, colsep=None, short=None):
    """Render a booktabs table with every column padded to the same width, so
    the generated file is as readable as a hand-written one."""
    # pad to the widest DATA cell of each column; the header (long labels) is
    # written as is so the data rows stay compact. header: one row, or a list
    # of rows (e.g. names, then units)
    heads = header if isinstance(header[0], list) else [header]
    rows = body + footer
    widths = [max(len(r[i]) for r in rows) for i in range(len(heads[0]))]

    def line(r, pad=True):
        cells = [cell.ljust(w) if pad else cell for cell, w in zip(r, widths)]
        return "  " + " & ".join(cells).rstrip() + " \\\\"

    out = [
        f"% {title}",
        "% Generated by train/model_2/evaluation/dataset_stats.py from the split files;",
        "% do not edit by hand - rerun the script instead.",
        "\\begin{table}[h]",
        "\\centering",
        "\\small",
        f"\\renewcommand{{\\arraystretch}}{{{stretch}}}",
        *([f"\\setlength{{\\tabcolsep}}{{{colsep}}}"] if colsep else []),
        f"\\caption[{short}]{{{caption}}}" if short else f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{colspec}}}",
        "\\toprule",
        *[line(h, pad=False) for h in heads],
        "\\midrule",
        *[line(r) for r in body],
    ]
    if footer:
        out += ["\\midrule", *[line(r) for r in footer]]
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(out)


def main():
    splits = {"train": TRAIN_JSON, "val": VAL_JSON, "test": TEST_JSON}
    counts = collections.Counter()
    area_pct = collections.defaultdict(list)
    wh = collections.defaultdict(list)
    sizes = collections.Counter()
    per_source = collections.defaultdict(lambda: {"frames": 0, "split": None, "classes": collections.Counter()})
    kpt = {"spray_total": 0, "spray_with_3_visible": 0}
    n_images = 0
    images_by_source = collections.defaultdict(list)
    per_split_images = {}

    for split, path in splits.items():
        d = json.load(open(path, encoding="utf-8"))
        cats = {c["id"]: c["name"] for c in d["categories"]}
        imgs = {i["id"]: i for i in d["images"]}
        per_split_images[split] = len(d["images"])
        n_images += len(d["images"])
        for i in d["images"]:
            sizes[(i["width"], i["height"])] += 1
            src = str(i.get("source_video"))
            base = src.split("_frames")[0]
            per_source[base]["frames"] += 1
            per_source[base]["split"] = split if per_source[base]["split"] in (None, split) else "train/val/test"
            images_by_source[base].append((i["file_name"], i.get("source_video")))
        for a in d["annotations"]:
            name = (a.get("_meta") or {}).get("original_class") or cats[a["category_id"]]
            counts[name] += 1
            im = imgs[a["image_id"]]
            base = str(im.get("source_video")).split("_frames")[0]
            per_source[base]["classes"][name] += 1
            if name in EXCLUDED_CATS:
                continue
            W, H = im["width"], im["height"]
            w, h = a["bbox"][2], a["bbox"][3]
            area_pct[name].append(100.0 * w * h / (W * H))
            wh[name].append((w, h))
            if name == "nozzle_spray":
                kpt["spray_total"] += 1
                k = a.get("keypoints") or []
                if sum(1 for v in k[2::3] if v > 0) == 3:
                    kpt["spray_with_3_visible"] += 1

    # ---- static-scene analysis on the cache
    static = {}
    for base, items in images_by_source.items():
        prev, runs, run = None, [], 0
        for fn, hint in sorted(items):
            arr = cv2.imread(str(cache_path_for(resolve_image_path(fn, hint))))
            if arr is None:
                continue
            small = cv2.resize(arr, (64, 48), interpolation=cv2.INTER_AREA).astype(np.int16)
            if prev is not None:
                if float(np.abs(small - prev).mean()) < STATIC_THRESH:
                    run += 1
                else:
                    runs.append(run + 1)
                    run = 0
            prev = small
        runs.append(run + 1)
        static[base] = {"scene_changes": len(runs), "longest_static_run": int(max(runs)), "median_run": float(np.median(runs))}

    assert len(sizes) == 1, sizes
    (W, H), _ = next(iter(sizes.items()))
    res = {
        "n_images": n_images, "images_per_split": per_split_images, "image_size": [W, H],
        "counts": dict(counts), "total_boxes": sum(counts.values()),
        "kept_boxes": sum(v for k, v in counts.items() if k not in EXCLUDED_CATS),
        "excluded": {k: v for k, v in counts.items() if k in EXCLUDED_CATS},
        "class_stats": {n: {"n": len(area_pct[n]), "median_area_px2": st.median(a * W * H / 100 for a in area_pct[n]),
                            "median_area_pct": st.median(area_pct[n]),
                            "mean_w": st.mean(w for w, _ in wh[n]), "mean_h": st.mean(h for _, h in wh[n])} for n in CLASS_ORDER},
        "keypoints": kpt,
        "per_source": {b: {"frames": v["frames"], "split": v["split"], "classes": dict(v["classes"]), **static.get(b, {})}
                       for b, v in sorted(per_source.items())},
        "static_thresh": STATIC_THRESH,
    }
    OUT_JSON.parent.mkdir(exist_ok=True)
    json.dump(res, open(OUT_JSON, "w"), indent=1)

    # ---- LaTeX tables ------------------------------------------------------
    # Both tables go through latex_table(), which pads every column so the
    # generated .tex stays readable (one aligned row per line).
    W, H = res["image_size"]

    # header cells in the classicthesis table style (spaced small caps); the
    # units stay outside the spaced letters so the row fits the text width
    header = ["\\spacedlowsmallcaps{Class}", "\\spacedlowsmallcaps{Boxes}", "\\spacedlowsmallcaps{Median area} (px\\textsuperscript{2})",
              "\\spacedlowsmallcaps{Mean w\\,$\\times$\\,h} (px)", "\\spacedlowsmallcaps{Share} (\\%)"]
    body = []
    for n in CLASS_ORDER:
        c = res["class_stats"][n]
        body.append([f"\\texttt{{{THESIS_NAME[n]}}}", fmt(c["n"]), fmt(round(c["median_area_px2"])),
                     f"{c['mean_w']:.0f}\\,$\\times$\\,{c['mean_h']:.0f}", f"{c['median_area_pct']:.1f}"])
    footer = [["\\textbf{Total}", f"\\textbf{{{fmt(res['kept_boxes'])}}}", "", "", ""]]
    excl_note = ""
    if res["excluded"]:
        excl = ", ".join(f"\\texttt{{{THESIS_NAME.get(k, k)}}} ({fmt(v)} boxes)" for k, v in res["excluded"].items())
        excl_note = f" A further annotated class, {excl}, is excluded from training and evaluation."
    # captions: wording chosen by the author (2026-09-20); keep them here so a
    # regeneration never overwrites them again
    caption1 = f"Class distribution and bounding box characteristics across the {fmt(n_images)} annotated frames.{excl_note}"
    (GEN_DIR / "tab-ch4-class-dist.tex").write_text(
        latex_table("Class counts and box sizes (Chapter 4, Table tab:ch5-class-dist)",
                    caption1, "tab:ch4-class-dist}\\label{tab:ch5-class-dist", "lrrrr", header, body, footer, stretch=1.25,
                    colsep="3.5pt", short="Class distribution and box sizes"),
        encoding="utf-8")

    order = ["CAM1 - V1", "CAM1 - V2", "CAM1 - V3", "CAM2 - V1", "CAM2 - V2", "CAM2 - V3",
             "20250508", "20250509", "20250510"]
    header = ["\\spacedlowsmallcaps{Recording}", "\\spacedlowsmallcaps{split}", "\\spacedlowsmallcaps{frames}",
              "\\texttt{spray}", "\\texttt{facing}", "\\texttt{no\\_spray}", "\\texttt{big}"]
    body = []
    for b in order:
        v, c = res["per_source"][b], res["per_source"][b]["classes"]
        body.append([SOURCE_LABEL.get(b, b), v["split"], fmt(v["frames"]),
                     fmt(c.get("nozzle_spray", 0)), fmt(c.get("nozzle_facing", 0)),
                     fmt(c.get("nozzle_no_spray", 0)), fmt(c.get("big_nozzle", 0))])
    caption2 = "Overview of the nine recordings. Each row reports its annotated frames, the box count per class, and the split tier."
    (GEN_DIR / "tab-ch4-sources.tex").write_text(
        latex_table("Recordings and per-source class counts (Chapter 4, Table tab:ch4-sources)",
                    caption2, "tab:ch4-sources", "lrrrrrr", header, body, [], stretch=1.2,
                    short="The nine recordings"),
        encoding="utf-8")

    print(json.dumps({k: res[k] for k in ("n_images", "images_per_split", "image_size", "counts", "kept_boxes", "keypoints")}, indent=1))
    for b in order:
        print(b, res["per_source"][b])
    print("wrote", OUT_JSON, "and", GEN_DIR)


if __name__ == "__main__":
    main()
