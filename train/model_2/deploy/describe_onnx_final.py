"""
describe_onnx_final.py - write a record of the exported final models to
deployment/pi5_final/MODELS.md, so the specifications are kept in git while
the ONNX files themselves stay ignored (deployment/pi5_final/models/).

For every ONNX file: size, SHA-256, opset, producer, parameter count, node
count, inputs and outputs with their shapes. For every seed: the source
checkpoint (SHA-256, epoch and validation composite when torch is available),
the gate threshold of the package, the Pi 5 timing (results/pi5_s{seed}.json)
and the ONNX / PyTorch parity on the test set (results/onnx_parity_test_final_cpu.json).

    python deploy/describe_onnx_final.py            (from train/model_2)
"""

import datetime
import hashlib
import json
from pathlib import Path

import onnx

HERE = Path(__file__).resolve().parent
MODEL2 = HERE.parent
REPO = MODEL2.parents[1]
PKG = REPO / "deployment" / "pi5_final"
RES = MODEL2 / "results"
CKPT = MODEL2 / "checkpoint"
OUT = PKG / "MODELS.md"

DTYPES = {1: "float32", 6: "int32", 7: "int64", 9: "bool", 10: "float16", 11: "float64"}


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def shape(value_info):
    dims = value_info.type.tensor_type.shape.dim
    return "[" + ", ".join(d.dim_param if d.dim_param else str(d.dim_value) for d in dims) + "]"


def describe(p):
    m = onnx.load(str(p))
    g = m.graph
    init_names = {i.name for i in g.initializer}
    n_params = 0
    for t in g.initializer:
        n = 1
        for d in t.dims:
            n *= d
        n_params += n
    ios = lambda xs: [(v.name, DTYPES.get(v.type.tensor_type.elem_type, str(v.type.tensor_type.elem_type)), shape(v))
                      for v in xs if v.name not in init_names]
    return {
        "file": p.name, "bytes": p.stat().st_size, "sha256": sha256(p),
        "opset": ", ".join(f"{o.domain or 'ai.onnx'} {o.version}" for o in m.opset_import),
        "ir": m.ir_version, "producer": f"{m.producer_name} {m.producer_version}".strip(),
        "params": n_params, "nodes": len(g.node), "inputs": ios(g.input), "outputs": ios(g.output),
    }


def checkpoint_info(run):
    p = CKPT / run / "afgnet_v10.pth"
    info = {"path": p.relative_to(REPO).as_posix(), "sha256": sha256(p) if p.exists() else "missing"}
    try:
        import torch
        ck = torch.load(p, map_location="cpu", weights_only=False)
        if isinstance(ck, dict):
            for k in ("epoch", "val_composite", "composite", "best_composite"):
                if k in ck:
                    info[k] = ck[k]
    except Exception as e:  # torch not installed in this interpreter, or another format
        info["note"] = f"epoch not read ({type(e).__name__})"
    return info


def main():
    cfg = json.load(open(PKG / "config.json", encoding="utf-8"))
    parity = json.load(open(RES / "onnx_parity_test_final_cpu.json", encoding="utf-8"))
    L = []
    L += ["# Exported final models (record)", "",
          f"Generated by `train/model_2/deploy/describe_onnx_final.py` on {datetime.date.today().isoformat()}. "
          "The ONNX files are not in git (`deployment/pi5_final/models/` is ignored); this file records what they are. "
          "Rebuild them with `python deploy/export_onnx_final.py` from `train/model_2`, then compare the SHA-256 below.", "",
          "Final model = run 7 (`abl_heads`), float32, no quantisation, exported with `torch.onnx.export` "
          "(opset 17, constant folding). Each seed has two graphs: the network (image to the grid outputs and the mist logits) "
          "and the angle reader (mist logits, tips and axes to the apex angle). Decoding, NMS and the mist gate run in numpy "
          "(`deployment/pi5_final/pipeline.py`).", "",
          "## Pipeline settings (`config.json`)", "",
          "| Setting | Value |", "|---|---|",
          f"| Input size | {cfg['img_w']} x {cfg['img_h']} (RGB, resize {cfg['resize']}) |",
          f"| Normalisation | mean {cfg['mean']}, std {cfg['std']} |",
          f"| Detection threshold | {cfg['obj_thresh']} |",
          f"| NMS IoU | {cfg['nms_iou']} |",
          f"| Gate disk radius | {cfg['tip_disk']} x max(w, h) of the box |",
          f"| Classes | {', '.join(cfg['class_names'])} |", ""]
    for sd, s in cfg["seeds"].items():
        run = f"abl_heads_s{sd}"
        ck = checkpoint_info(run)
        L += [f"## Seed {sd}", "",
              f"Source checkpoint `{ck['path']}`, SHA-256 `{ck['sha256']}`"
              + "".join(f", {k} {v:.4f}" if isinstance(v, float) else f", {k} {v}"
                        for k, v in ck.items() if k not in ("path", "sha256")) + ".",
              f"Gate threshold {s['gate_threshold']}.", ""]
        for name in (s["main"], s["reader"]):
            p = PKG / "models" / name
            if not p.exists():
                L += [f"`{name}`: file not present when this record was written.", ""]
                continue
            d = describe(p)
            L += [f"### `{d['file']}`", "",
                  "| Property | Value |", "|---|---|",
                  f"| Size | {d['bytes']:,} bytes ({d['bytes'] / 2**20:.2f} MiB) |",
                  f"| SHA-256 | `{d['sha256']}` |",
                  f"| Opset | {d['opset']} |",
                  f"| IR version | {d['ir']} |",
                  f"| Producer | {d['producer']} |",
                  f"| Parameters | {d['params']:,} |",
                  f"| Nodes | {d['nodes']:,} |", "",
                  "| Direction | Name | Type | Shape |", "|---|---|---|---|"]
            L += [f"| input | `{n}` | {t} | {sh} |" for n, t, sh in d["inputs"]]
            L += [f"| output | `{n}` | {t} | {sh} |" for n, t, sh in d["outputs"]]
            L += [""]
        pi = RES / f"pi5_s{sd}.json"
        if pi.exists():
            b = json.load(open(pi, encoding="utf-8"))
            t = b["time_ms"]
            L += ["Raspberry Pi 5 (`train/model_2/results/" + pi.name + "`, "
                  f"{b['protocol']['count']} frames after {b['protocol']['warmup']} warm-up, {b['protocol']['threads']} threads): "
                  f"total {t['total']['mean']:.1f} ms mean, forward {t['forward']['mean']:.1f} ms, "
                  f"readers {t['readers']['mean']:.1f} ms, {b['fps']['sustained']:.2f} FPS sustained, "
                  f"resident memory {b['rss_mb']['peak']:.0f} MB peak.", ""]
        pr = parity.get(sd) or parity.get(int(sd))
        if pr:
            L += [f"Parity with PyTorch float32 on the CPU over the {pr['frames']} test frames: "
                  f"{len(pr['n_det_differ'])} frames with a different detection count, "
                  f"{len(pr['state_differ'])} different states, box difference up to {pr['box_max_abs']:.1e}, "
                  f"angle difference up to {pr['angle_max_abs_deg']:.1e} degrees "
                  "(`train/model_2/results/onnx_parity_test_final_cpu.json`).", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
